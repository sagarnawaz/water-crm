-- Paani Register: initial schema, tenant isolation (RLS) and audit log.
-- Rules: docs/BUSINESS_RULES.md · Design: docs/ARCHITECTURE.md
-- All money is integer rupees.

-- ---------------------------------------------------------------------------
-- Tenancy
-- ---------------------------------------------------------------------------
create table public.businesses (
  id           uuid primary key default gen_random_uuid(),
  name         text not null check (length(trim(name)) > 0),
  default_rate int  not null default 100 check (default_rate > 0),  -- price for floors not in floor_prices
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create table public.memberships (
  user_id     uuid not null references auth.users(id) on delete cascade,
  business_id uuid not null references public.businesses(id) on delete cascade,
  role        text not null default 'owner' check (role in ('owner')),
  created_at  timestamptz not null default now(),
  primary key (user_id, business_id)
);

-- security definer so policies can read memberships without recursing into its own RLS
create function public.my_business_ids() returns setof uuid
language sql stable security definer set search_path = public as $$
  select business_id from public.memberships where user_id = auth.uid()
$$;

-- Default business_id for new rows. RLS "with check" still rejects any other value a client sends.
create function public.current_business_id() returns uuid
language sql stable security definer set search_path = public as $$
  select business_id from public.memberships where user_id = auth.uid() order by created_at limit 1
$$;

-- ---------------------------------------------------------------------------
-- Data tables
-- ---------------------------------------------------------------------------
create table public.floor_prices (
  business_id uuid not null default public.current_business_id() references public.businesses(id) on delete cascade,
  floor       text not null check (length(trim(floor)) > 0),
  price       int  not null check (price > 0),
  updated_at  timestamptz not null default now(),
  primary key (business_id, floor)
);

create table public.customers (
  id              uuid primary key default gen_random_uuid(),
  business_id     uuid not null default public.current_business_id() references public.businesses(id) on delete cascade,
  house_no        text not null check (length(trim(house_no)) > 0),
  floor           text not null check (length(trim(floor)) > 0),
  area            text not null check (length(trim(area)) > 0),
  name            text,
  phone           text,
  billing_type    text not null default 'monthly' check (billing_type in ('monthly', 'daily')),
  custom_rate     int check (custom_rate > 0),            -- null = use the floor price
  default_qty     int check (default_qty > 0),            -- null = on request
  opening_balance int not null default 0,                 -- from the paper register; negative = advance
  opening_bottles int not null default 0 check (opening_bottles >= 0),
  active          boolean not null default true,
  notes           text,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  unique (id, business_id)                                -- target for same-business foreign keys below
);
create unique index customers_unique_address on public.customers
  (business_id, lower(trim(house_no)), lower(trim(floor)), lower(trim(area))) where active;

create table public.deliveries (
  id               uuid primary key,                      -- generated by the client so a repeated save does nothing
  business_id      uuid not null default public.current_business_id() references public.businesses(id) on delete cascade,
  customer_id      uuid not null,
  date             date not null,
  qty              int  not null check (qty >= 0),
  empties_returned int  not null default 0 check (empties_returned >= 0),
  rate             int  not null check (rate > 0),        -- price copied at entry time (filled by trigger)
  amount           int  generated always as (qty * rate) stored,
  note             text,
  deleted_at       timestamptz,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  check (qty + empties_returned > 0),
  foreign key (customer_id, business_id) references public.customers (id, business_id)
);
create index deliveries_customer_date on public.deliveries (customer_id, date);  -- not unique: several per day allowed

create table public.payments (
  id          uuid primary key,                           -- generated by the client so a repeated save does nothing
  business_id uuid not null default public.current_business_id() references public.businesses(id) on delete cascade,
  customer_id uuid not null,
  date        date not null,
  amount      int  not null check (amount > 0 and amount <= 1000000),
  method      text not null check (method in ('cash_rider', 'cash_owner', 'online')),
  for_month   date check (for_month = date_trunc('month', for_month)::date),  -- monthly customers: 1st of the bill month
  note        text,
  deleted_at  timestamptz,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  foreign key (customer_id, business_id) references public.customers (id, business_id)
);
create index payments_customer_date on public.payments (customer_id, date);

create table public.audit_log (
  id          bigserial primary key,
  business_id uuid,
  table_name  text not null,
  row_id      text not null,
  action      text not null,
  old         jsonb,
  new         jsonb,
  user_id     uuid default auth.uid(),
  at          timestamptz not null default now()
);
create index audit_log_business_at on public.audit_log (business_id, at desc);

-- ---------------------------------------------------------------------------
-- Triggers
