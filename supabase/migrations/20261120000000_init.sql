create function public.set_updated_at() returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end $$;

create trigger businesses_updated_at   before update on public.businesses   for each row execute function public.set_updated_at();
create trigger floor_prices_updated_at before update on public.floor_prices for each row execute function public.set_updated_at();
create trigger customers_updated_at    before update on public.customers    for each row execute function public.set_updated_at();
create trigger deliveries_updated_at   before update on public.deliveries   for each row execute function public.set_updated_at();
create trigger payments_updated_at     before update on public.payments     for each row execute function public.set_updated_at();

-- Effective price = custom rate, else floor price, else the business default.
create function public.effective_rate(p_customer_id uuid) returns int
language sql stable as $$
  select coalesce(c.custom_rate, fp.price, b.default_rate)
  from public.customers c
  join public.businesses b on b.id = c.business_id
  left join public.floor_prices fp on fp.business_id = c.business_id and fp.floor = c.floor
  where c.id = p_customer_id
$$;

-- New deliveries: customer must be active; copy the current price unless the app sent one.
create function public.deliveries_before_insert() returns trigger language plpgsql as $$
begin
  if not exists (select 1 from public.customers where id = new.customer_id and active) then
    raise exception 'Customer is inactive or does not exist' using errcode = 'check_violation';
  end if;
  if new.rate is null then
    new.rate := public.effective_rate(new.customer_id);
  end if;
  return new;
end $$;
create trigger deliveries_fill_rate before insert on public.deliveries
  for each row execute function public.deliveries_before_insert();

-- Every change to money or customer data is kept.
create function public.audit() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  r jsonb := to_jsonb(coalesce(new, old));
begin
  insert into public.audit_log (business_id, table_name, row_id, action, old, new)
  values (
    (r->>'business_id')::uuid,
    tg_table_name,
    coalesce(r->>'id', r->>'floor'),
    lower(tg_op),
    case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) end,
    case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) end
  );
  return coalesce(new, old);
end $$;

create trigger customers_audit    after insert or update or delete on public.customers    for each row execute function public.audit();
create trigger deliveries_audit   after insert or update or delete on public.deliveries   for each row execute function public.audit();
create trigger payments_audit     after insert or update or delete on public.payments     for each row execute function public.audit();
create trigger floor_prices_audit after insert or update or delete on public.floor_prices for each row execute function public.audit();

-- ---------------------------------------------------------------------------
-- Row Level Security: a user sees only the businesses they belong to.
-- Businesses and memberships are created by us with the service role (scripts/create-owner.mjs).
-- Deliveries, payments and customers are never hard-deleted by the app (soft delete / deactivate).
-- ---------------------------------------------------------------------------
alter table public.businesses   enable row level security;
alter table public.memberships  enable row level security;
alter table public.floor_prices enable row level security;
alter table public.customers    enable row level security;
alter table public.deliveries   enable row level security;
alter table public.payments     enable row level security;
alter table public.audit_log    enable row level security;

create policy businesses_select on public.businesses for select to authenticated
  using (id in (select public.my_business_ids()));
create policy businesses_update on public.businesses for update to authenticated
  using (id in (select public.my_business_ids())) with check (id in (select public.my_business_ids()));

create policy memberships_select on public.memberships for select to authenticated
  using (user_id = auth.uid());

create policy floor_prices_all on public.floor_prices for all to authenticated
  using (business_id in (select public.my_business_ids()))
  with check (business_id in (select public.my_business_ids()));

